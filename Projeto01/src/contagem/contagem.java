package contagem;
public class contagem {
    static void main() {
        System.out.println("vamos contar até 10");
        for (int n = 0; n <=10 ;n++){
            System.out.println(n);
        }
        System.out.println("cabou.");

        System.out.println("agora contar os pares de 1 até 20");
        for (var a = 2; a <=20; a +=2) {
            System.out.println(a);
        }
    }

}
